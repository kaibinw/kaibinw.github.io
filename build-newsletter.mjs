#!/usr/bin/env node
// Builds the /newsletter/ pages (sign-up, check-your-inbox, confirmed). Zero dependencies, Node 18+.
//
//   node build-newsletter.mjs
//
// Reads newsletter/config.json. The sign-up form is only emitted when "enabled" is true and formAction is an
// absolute https: URL. The landing page is noindex until enabled; check-email and confirmed are always noindex.
// After changing config.json, run this AND build-blog.mjs (post forms are baked into the blog HTML).
// Blog-post sign-up forms are injected by build-blog.mjs from the same config.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { signupForm, formReady } from './newsletter/form.mjs';

const ROOT = dirname(fileURLToPath(import.meta.url));
const SITE = 'https://kaibinw.github.io';
const MARK = '<!-- generated by build-newsletter.mjs — edit the script, not this file -->';
const cfg = JSON.parse(readFileSync(join(ROOT, 'newsletter', 'config.json'), 'utf8'));
if (cfg.enabled && !formReady(cfg)) console.warn('newsletter: enabled but formAction is not an absolute https: URL; forms are omitted');

// sidebar and footer are borrowed from a case study so they never drift; no nav item is active here
const donor = readFileSync(join(ROOT, 'case-studies', 'ledger.html'), 'utf8');
const grab = (re) => { const m = donor.match(re); if (!m) throw new Error('case-studies/ledger.html: chrome not found'); return m[0]; };
const sidebar = grab(/<aside class="sidebar">[\s\S]*?<\/aside>/)
  .replace(/ active(?=")/g, '').replace(/ aria-current="page"/g, '')
  .replace('<details class="side-group" open>', '<details class="side-group">')
  .replace(/CASE \d+ OF \d+/, 'NEWSLETTER')
  .replace(/href="(?!https?:|mailto:|#|\.\.\/)([^"]+)"/g, 'href="../case-studies/$1"');
const footer = grab(/<footer class="site-foot">[\s\S]*?<\/footer>/);

const page = ({ file, title, description, body, indexable = false }) => `<!DOCTYPE html>
${MARK}
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>${title}</title>
<meta name="description" content="${description}">
<meta name="referrer" content="no-referrer">
<meta property="og:title" content="${title}">
<meta property="og:description" content="${description}">
<meta property="og:type" content="website">
<meta property="og:url" content="${SITE}/newsletter/${file === 'index.html' ? '' : file}">
<meta property="og:image" content="${SITE}/og.png">
<meta name="twitter:card" content="summary_large_image">
${cfg.enabled && indexable ? `<link rel="canonical" href="${SITE}/newsletter/${file === 'index.html' ? '' : file}">` : '<meta name="robots" content="noindex, nofollow">'}
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="preload" as="style" href="https://fonts.googleapis.com/css2?family=Familjen+Grotesk:wght@400;500;700&family=Fragment+Mono&display=swap" onload="this.onload=null;this.rel='stylesheet'">
<noscript><link href="https://fonts.googleapis.com/css2?family=Familjen+Grotesk:wght@400;500;700&family=Fragment+Mono&display=swap" rel="stylesheet"></noscript>
<link rel="icon" href="../favicon.svg" type="image/svg+xml">
<link rel="icon" href="../favicon.ico" sizes="32x32">
<link rel="apple-touch-icon" href="../apple-touch-icon.png">
<link rel="stylesheet" href="../style.css">
<link rel="stylesheet" href="../newsletter/newsletter.css">
</head>
<body>

<a class="skip-link" href="#main">Skip to content</a>

${sidebar}

<main class="content" id="main">

<section aria-labelledby="nl-page-title">
  <div class="wrap">
${body}
  </div>
</section>

${footer}

</main>

</body>
</html>
`;

const pages = [
  {
    file: 'index.html',
    indexable: true,
    title: 'Get new posts by email — Kai-Bin Wong',
    description: 'One short email when a new post goes up.',
    body: `    <p class="tc">TC 01:09:40:00 — NEWSLETTER</p>
    <h1 class="section-title" id="nl-page-title">Get new posts by email.</h1>
    <p>Notes from a VFX editor who ships software. Confirm your address by email first; unsubscribe in one click.</p>
${signupForm(cfg, 'page').replace(/^/gm, '    ')}
    <p><a class="work-link" href="../blog/index.html">Read the blog</a></p>`,
  },
  {
    file: 'check-email.html',
    title: 'Check your inbox — Kai-Bin Wong',
    description: 'Confirm your email address to finish signing up.',
    body: `    <p class="tc">TC 01:09:40:00 — NEWSLETTER</p>
    <h1 class="section-title" id="nl-page-title">Check your inbox.</h1>
    <p>I've sent you a confirmation email. Click the link in it to finish signing up. If it hasn't arrived in a few minutes, look in spam.</p>
    <p><a class="work-link" href="../blog/index.html">Read the blog while you wait</a></p>`,
  },
  {
    file: 'confirmed.html',
    title: "You're in — Kai-Bin Wong",
    description: 'Your email address is confirmed.',
    body: `    <p class="tc">TC 01:09:40:00 — NEWSLETTER</p>
    <h1 class="section-title" id="nl-page-title">You're in.</h1>
    <p>Your address is confirmed. You'll get one short email when the next post goes up.</p>
    <p><a class="work-link" href="../blog/index.html">Read the blog</a></p>`,
  },
];

for (const p of pages) writeFileSync(join(ROOT, 'newsletter', p.file), page(p));
console.log(`newsletter: ${pages.length} pages, ${cfg.enabled ? 'ENABLED (landing page indexable)' : 'disabled (noindex)'}`);
